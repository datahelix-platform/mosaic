"""Main CLI entry point for Mosaic."""

import typer
from pathlib import Path
from typing import List, Optional

app = typer.Typer(
    name="mosaic",
    help="Mosaic — a runtime for LinkML schemas. Run a schema as a service with typed SDK, REST API, and PROV-O provenance.",
    add_completion=False,
)


@app.command()
def init(
    path: Optional[str] = typer.Option(
        None, "--path", "-p", help="Project directory path"
    ),
    template: str = typer.Option(
        "bibliography",
        "--template",
        "-t",
        help="Template to use (bibliography, basic, minimal, full)",
    ),
    storage: str = typer.Option(
        "sqlite",
        "--storage",
        "-s",
        help="Storage backend: sqlite or postgres",
    ),
    force: bool = typer.Option(
        False, "--force", "-f", help="Force initialization even if directory exists"
    ),
) -> None:
    """Initialize a new Mosaic project."""
    from mosaic.cli.commands.init import run_init

    run_init(path=path, template=template, force=force, storage=storage)


@app.command()
def serve(
    host: str = typer.Option(
        "127.0.0.1", "--host", "-h", help="Host address to bind the server to"
    ),
    port: int = typer.Option(8000, "--port", "-p", help="Port number to listen on"),
    reload: bool = typer.Option(
        False, "--reload", "-r", help="Enable auto-reload during development"
    ),
    workers: int = typer.Option(
        None,
        "--workers",
        "-w",
        help="Number of worker processes to use (defaults to 1)",
    ),
    reload_dir: Optional[List[str]] = typer.Option(
        None,
        "--reload-dir",
        help=(
            "Directory to watch for source changes when --reload is set "
            "(repeatable). Only meaningful with --reload. Defaults to the "
            "directory containing the imported 'mosaic' package rather than "
            "the current working directory — cwd must stay the project "
            "directory so schema_path/database_url in the config keep "
            "resolving correctly (issue #174)."
        ),
    ),
    log_level: str = typer.Option(
        "info",
        "--log-level",
        "-l",
        help="Set the logging level (debug, info, warning, error)",
    ),
    config: str = typer.Option(
        None,
        "--config",
        "-c",
        help=(
            "Path to a Mosaic config (config.json / mosaic.yaml). If omitted, "
            "one is auto-detected in the current directory; otherwise the "
            "server falls back to a default SQLite database."
        ),
    ),
    graphql: bool = typer.Option(
        False,
        "--graphql",
        help=(
            "Also mount the autogenerated GraphQL API (with GraphiQL) at "
            "/graphql. Requires the optional 'graphql' extra and a "
            "schema-backed deployment (config with a schema_path)."
        ),
    ),
    graphql_max_depth: int = typer.Option(
        None,
        "--graphql-max-depth",
        help=(
            "Maximum GraphQL query nesting depth (default 10). Only "
            "meaningful with --graphql."
        ),
    ),
    mcp: bool = typer.Option(
        False,
        "--mcp",
        help=(
            "Also mount the MCP (Model Context Protocol) transport at "
            "/mcp — schema and capability-manifest resources (ADR-0009). "
            "Requires the optional 'mcp' extra and a schema-backed "
            "deployment (config with a schema_path). Read-only: no write "
            "or mutation tool exists on this surface."
        ),
    ),
    cors_origin: Optional[List[str]] = typer.Option(
        None,
        "--cors-origin",
        help=(
            "Origin allowed to make cross-origin requests against REST, "
            "GraphQL, and MCP alike (repeatable). Off by default — no "
            "CORS headers are sent unless at least one origin is given "
            "here or via 'cors_allow_origins' in mosaic.yaml (issue "
            "#207). No '*' default: an explicit list only."
        ),
    ),
) -> None:
    """Start the REST API server with customizable configuration.

    The server serves the deployment described by the resolved config —
    storage backend, schema, and validators — built through the same SDK
    factory the CLI and TUI use, so REST, SDK, and TUI all open the same
    instance the same way.

    Usage:
      mosaic serve                       # Auto-detect config in the cwd
      mosaic serve --config mosaic.yaml  # Explicit config
      mosaic serve --port 9000           # Start on custom port
      mosaic serve --log-level debug     # Start with debug logging
      mosaic serve --graphql             # Also serve GraphQL at /graphql
      mosaic serve --mcp                 # Also serve MCP at /mcp
      mosaic serve --reload --reload-dir /src  # Watch a mounted source tree
      mosaic serve --graphql --cors-origin http://localhost:5173  # Allow a browser origin
    """
    import uvicorn

    from mosaic.config import ConfigError
    from mosaic.config import ValidationError as ConfigValidationError
    from mosaic.core.factory import (
        DEFAULT_SQLITE_PATH,
        create_client,
        create_client_from_config,
        load_config_autodetect,
    )
    from mosaic.serve import create_default_app

    try:
        cfg = load_config_autodetect(config)
    except (ConfigError, ConfigValidationError) as exc:
        if config is not None:
            # An explicitly-requested config must be valid — fail loudly.
            typer.echo(f"Error: could not load config {config!r}: {exc}", err=True)
            raise typer.Exit(1)
        typer.echo(f"Warning: ignoring malformed config in cwd: {exc}", err=True)
        cfg = None

    if cfg is not None:
        client = create_client_from_config(cfg)
        backend = cfg.storage_backend or "sqlite"
        typer.echo(
            f"Serving {backend} deployment "
            f"(schema: {cfg.schema_path}, db: {cfg.database_url or 'default'})"
        )
    else:
        client = create_client()
        typer.echo(
            f"No config found; serving a default SQLite database at "
            f"{DEFAULT_SQLITE_PATH} with the bundled mosaic_core schema"
        )

    cors_allow_origins = (
        list(cors_origin) if cors_origin else (cfg.cors_allow_origins if cfg else None)
    )

    typer.echo(f"Starting Mosaic server on {host}:{port} with log level {log_level}")
    try:
        app = create_default_app(
            client,
            graphql=graphql,
            graphql_max_query_depth=graphql_max_depth,
            mcp=mcp,
            cors_allow_origins=cors_allow_origins,
        )
    except ImportError as exc:
        # Missing `graphql`/`mcp` extra — fail with the actionable hint.
        typer.echo(f"Error: {exc}", err=True)
        raise typer.Exit(1)
    except ConfigError as exc:
        # e.g. --graphql/--mcp against a deployment without a schema registry.
        typer.echo(f"Error: {exc}", err=True)
        raise typer.Exit(1)
    if graphql:
        typer.echo(
            f"GraphQL API (GraphiQL) available at http://{host}:{port}/graphql"
        )
    if mcp:
        typer.echo(f"MCP transport available at http://{host}:{port}/mcp")
    if cors_allow_origins:
        typer.echo(f"CORS enabled for origins: {', '.join(cors_allow_origins)}")
    # Note: Uvicorn's logging is currently configured through uvicorn configuration,
    # so we might need to pass it explicitly if needed
    if reload or workers:
        # --reload/--workers re-import the app in fresh subprocess(es), so
        # uvicorn needs an import string rather than the app object built
        # above (issue #171). Thread the resolved config through the
        # environment so those subprocesses rebuild the identical
        # deployment this process just resolved.
        import os

        if config is not None:
            os.environ["MOSAIC_CONFIG"] = config
        if graphql:
            os.environ["MOSAIC_SERVE_GRAPHQL"] = "1"
        if graphql_max_depth is not None:
            os.environ["MOSAIC_SERVE_GRAPHQL_MAX_DEPTH"] = str(graphql_max_depth)
        if mcp:
            os.environ["MOSAIC_SERVE_MCP"] = "1"
        if cors_allow_origins:
            os.environ["MOSAIC_SERVE_CORS_ORIGINS"] = ",".join(cors_allow_origins)

        reload_dirs = None
        if reload:
            # uvicorn defaults reload_dirs to cwd, which is the *project*
            # directory here (schema_path/database_url resolve against it) —
            # not necessarily where mosaic's own source lives (e.g. a
            # PYTHONPATH-mounted checkout shadowing the installed package).
            # Watch the resolved 'mosaic' package directory instead unless
            # the caller pins explicit directories (issue #174).
            if reload_dir:
                reload_dirs = list(reload_dir)
            else:
                import mosaic as _mosaic_pkg

                reload_dirs = [str(Path(_mosaic_pkg.__file__).resolve().parent)]
            typer.echo(f"Watching for reload in: {', '.join(reload_dirs)}")

        uvicorn.run(
            "mosaic.serve:create_app_from_env",
            factory=True,
            host=host,
            port=port,
            reload=reload,
            reload_dirs=reload_dirs,
            workers=workers,
            log_level=log_level.lower(),
        )
    else:
        uvicorn.run(app, host=host, port=port, log_level=log_level.lower())


@app.command()
def migrate(
    target: str = typer.Argument(None, help="Target version (not used in v0.1)"),
    dry_run: bool = typer.Option(
        False, "--dry-run", "--preview", help="Preview migrations without applying"
    ),
    schema_dir: str = typer.Option(
        None, "--schema-dir", help="Path to schema directory (default: schemas/)"
    ),
    db_path: str = typer.Option(
        None, "--db-path", help="Path to SQLite database (default: data/mosaic.db)"
    ),
) -> None:
    """Run schema migrations based on YAML schema definitions."""
    import sqlite3
    from pathlib import Path

    if schema_dir:
        schemas_path = Path(schema_dir)
    else:
        schemas_path = Path("schemas")

    if not schemas_path.exists():
        typer.echo(f"Error: Schema directory not found: {schemas_path}", err=True)
        raise typer.Exit(1)

    schema_files = list(schemas_path.glob("*.yaml")) + list(schemas_path.glob("*.yml"))
    if not schema_files:
        typer.echo(f"No schema files found in {schemas_path}")
        typer.echo("No migrations needed")
        return

    if db_path:
        database_path = Path(db_path)
    else:
        from mosaic.core.factory import default_sqlite_path

        database_path = Path(default_sqlite_path())

    if not database_path.exists():
        typer.echo(f"Error: Database not found: {database_path}", err=True)
        typer.echo(
            "Please initialize the database first with 'mosaic init' or create a new database.",
            err=True,
        )
        raise typer.Exit(1)

    try:
        conn = sqlite3.connect(str(database_path))
        conn.row_factory = sqlite3.Row
        cursor = conn.cursor()

        from mosaic.core.storage.schema_diff import diff_registry_against_database
        from mosaic.core.storage.migration import MigrationPlanner, MigrationExecutor
        from mosaic.core.factory import build_schema_registry

        # merge_requires=True spans the registry over the schema's installed
        # `requires:` loaders, so a slot ranged on a loader class is planned
        # correctly and the `requires:` gate runs before any DDL (closes the
        # docs' "mosaic migrate also checks requires:" claim — issue #67).
        registry = build_schema_registry(schemas_path, merge_requires=True)
        engine, schema_diff = diff_registry_against_database(registry, cursor)

        if (
            not schema_diff.new_tables
            and not schema_diff.new_columns
            and not schema_diff.new_indexes
        ):
            typer.echo("No schema changes detected")
            typer.echo("No migrations needed")
            conn.close()
            return

        planner = MigrationPlanner()
        planner.load_existing_fts_tables(cursor)
        plan = planner.plan_migration_from_diff(schema_diff, registry, cursor)

        typer.echo("=== Migration Plan ===")
        typer.echo("")

        if plan.new_tables:
            typer.echo(f"New tables to create ({len(plan.new_tables)}):")
            for table in plan.new_tables:
                typer.echo(f"  + {table}")
            typer.echo("")

        if plan.modified_tables:
            typer.echo(f"Tables to modify ({len(plan.modified_tables)}):")
            for table in plan.modified_tables:
                typer.echo(f"  ~ {table}")
            typer.echo("")

        if plan.warnings:
            typer.echo("Warnings:")
            for warning in plan.warnings:
                typer.echo(f"  ! {warning}")
            typer.echo("")

        if dry_run:
            typer.echo("=== DDL Statements (Preview) ===")
            typer.echo("")

            if plan.ddl_statements:
                typer.echo("-- Create new tables --")
                for stmt in plan.ddl_statements:
                    typer.echo(stmt)
                    typer.echo("")

            if plan.alter_table_statements:
                typer.echo("-- Add new columns --")
                for stmt in plan.alter_table_statements:
                    typer.echo(stmt)
                typer.echo("")

            if plan.create_index_statements:
                typer.echo("-- Create new indexes --")
                for stmt in plan.create_index_statements:
                    typer.echo(stmt)
                typer.echo("")

            if plan.fts_ddl_statements:
                typer.echo("-- Create FTS tables --")
                for stmt in plan.fts_ddl_statements:
                    typer.echo(stmt)
                typer.echo("")

            typer.echo("Preview complete. No changes applied.")
            conn.close()
            return

        executor = MigrationExecutor(conn)
        result = executor.execute_migration(plan)
        conn.commit()
        conn.close()

        if result.success:
            typer.echo("=== Migration Complete ===")
            typer.echo(f"Tables created: {len(result.tables_created)}")
            typer.echo(f"Tables modified: {len(result.tables_modified or [])}")
            typer.echo(f"FTS tables created: {len(result.fts_tables_created or [])}")
            typer.echo(f"Records backfilled: {result.records_backfilled}")

            if result.warnings:
                typer.echo("")
                typer.echo("Warnings:")
                for warning in result.warnings:
                    typer.echo(f"  ! {warning}")
        else:
            typer.echo("Migration failed with errors:", err=True)
            for error in result.errors or []:
                typer.echo(f"  - {error}", err=True)
            raise typer.Exit(1)

    except Exception as e:
        typer.echo(f"Error during migration: {e}", err=True)
        raise typer.Exit(1)


@app.command()
def validate(
    schema: str = typer.Option(
        None, "--schema", "-s", help="Path to a LinkML schema file or directory"
    ),
    data: str = typer.Option(
        None,
        "--data",
        "-d",
        help="Path to an instance YAML bundle to validate against --schema",
    ),
    config: str = typer.Option(
        None, "--config", "-c", help="Path to config file to validate"
    ),
    verbose: bool = typer.Option(
        False, "--verbose", "-v", help="Show detailed validation output"
    ),
) -> None:
    """Validate a LinkML schema and/or an instance YAML bundle.

    Usage:
      mosaic validate                                   # Validate default configuration
      mosaic validate --schema schema.yaml              # Validate LinkML schema only
      mosaic validate --schema schema.yaml --data bundle.yaml
                                                       # Validate instance bundle against schema
      mosaic validate --config my-config.yaml           # Validate Mosaic config file shape
    """
    from pathlib import Path
    import yaml

    if config and not Path(config).exists():
        typer.echo(f"Error: Configuration file not found: {config}", err=True)
        raise typer.Exit(1)

    if schema and not Path(schema).exists():
        typer.echo(f"Error: Schema file not found: {schema}", err=True)
        raise typer.Exit(1)

    if data and not schema:
        typer.echo("Error: --data requires --schema", err=True)
        raise typer.Exit(1)

    if data and not Path(data).exists():
        typer.echo(f"Error: Data file not found: {data}", err=True)
        raise typer.Exit(1)

    if not schema and not config:
        typer.echo("Validating default Mosaic configuration...")
        typer.echo("Default configuration is valid")
        return

    registry = None
    if schema:
        from mosaic.linkml_bridge import SchemaRegistry
        from mosaic.requires import check_requires, extract_requires
        from mosaic.core.exceptions import SchemaError

        typer.echo(f"Validating schema: {schema}")
        try:
            registry = SchemaRegistry.from_path(schema)
        except Exception as e:
            typer.echo(f"Error: Invalid LinkML schema: {e}", err=True)
            raise typer.Exit(1)
        typer.echo(
            f"Schema is valid LinkML with {len(registry.class_names())} classes."
        )

        # PTS-227 — `requires:` directive (exact-match v1).
        try:
            pins = extract_requires(schema)
        except SchemaError as e:
            typer.echo(f"Error: Invalid `requires:` in {schema}: {e.message}", err=True)
            raise typer.Exit(1)
        if pins:
            require_errors = check_requires(pins)
            if require_errors:
                typer.echo(
                    f"Error: {schema}: {len(require_errors)} reference-loader "
                    f"requirement error(s):",
                    err=True,
                )
                for msg in require_errors:
                    typer.echo(f"  - {msg}", err=True)
                raise typer.Exit(1)
            typer.echo(
                f"`requires:` satisfied — {len(pins)} reference loader(s) pinned."
            )
            # Span the registry over the pinned loaders so a `--data` bundle
            # validates against loader-provided classes too (issue #67). The
            # version gate already passed above, so skip re-checking here.
            from mosaic.core.loaders.discovery import fragment_specs_for_requires

            specs = fragment_specs_for_requires(schema, check_versions=False)
            if specs:
                registry = registry.with_loader_fragments(specs)

    if data:
        assert registry is not None
        typer.echo(f"Validating data: {data}")
        try:
            content = yaml.safe_load(Path(data).read_text())
        except yaml.YAMLError as e:
            typer.echo(f"Error: Failed to parse {data}: {e}", err=True)
            raise typer.Exit(1)

        if not isinstance(content, dict):
            typer.echo(
                f"Error: {data}: expected a YAML mapping at the top level "
                f"(tree-root bundle), got {type(content).__name__}",
                err=True,
            )
            raise typer.Exit(1)

        errors = registry.validate(content, registry.tree_root_class_name())
        if errors:
            typer.echo(f"Error: {data}: {len(errors)} validation error(s):", err=True)
            for err in errors:
                typer.echo(f"  - {err}", err=True)
            raise typer.Exit(1)

    if config:
        typer.echo(f"Validating config: {config}")
        try:
            config_content = yaml.safe_load(Path(config).read_text())
        except yaml.YAMLError as e:
            typer.echo(f"Error: Failed to parse {config}: {e}", err=True)
            raise typer.Exit(1)

        if not isinstance(config_content, dict):
            typer.echo(
                "Error: Invalid config format - expected dictionary", err=True
            )
            raise typer.Exit(1)

    typer.echo("Validation complete - all checks passed")


def _build_schema_registry(schema_path: str | None = None):
    """Build a SchemaRegistry from ``schema_path`` or the bundled mosaic_core schema.

    The bundled schema only declares Mosaic's framework classes (Entity,
    ProvenanceRecord, ExternalID, ...). Callers that need user-domain
    classes (Sample, Project, ...) must pass an explicit ``schema_path``.

    The registry spans the schema's installed ``requires:`` loaders so an
    ingested bundle validates against loader-provided classes too (issue
    #67); a schema with no ``requires:`` is unaffected.
    """
    from mosaic.core.factory import build_schema_registry

    return build_schema_registry(schema_path, merge_requires=True)


def _get_client(db_path: str | None = None, schema_path: str | None = None):
    """Construct a MosaicClient via the shared config-driven factory.

    Looks for the database at --db-path, then data/mosaic.db. When
    ``schema_path`` is provided, the storage adapter is wired to a
    SchemaRegistry built from that path so writes of user-domain classes
    validate correctly; otherwise only the bundled mosaic_core classes
    are recognized.
    """
    from mosaic.core.factory import create_client

    return create_client(
        database_url=str(db_path) if db_path else None,
        schema_path=schema_path,
    )


@app.command()
def ingest(
    file: str = typer.Option(
        None,
        "--file",
        "-f",
        help="Path to a LinkML-native instance YAML bundle to ingest",
    ),
    loader_type: str = typer.Option(
        None, "--type", "-t", help="Loader type: csv, json, or sql"
    ),
    config: str = typer.Option(
        None,
        "--config",
        "-c",
        help="Path to loader config file (for --type csv/json/sql)",
    ),
    validate_schema: str = typer.Option(
        None,
        "--validate-schema",
        help=(
            "Path to a LinkML schema file or directory. The bundle is "
            "validated against this schema's tree-root before any writes; "
            "the same schema backs the storage adapter so user-domain "
            "classes are recognized."
        ),
    ),
    db_path: str = typer.Option(
        None,
        "--db-path",
        help="Path to SQLite database (default: data/mosaic.db)",
    ),
    dry_run: bool = typer.Option(
        False, "--dry-run", help="Show what would be written without writing"
    ),
) -> None:
    """Ingest a LinkML-native instance YAML bundle into Mosaic.

    The bundle is a YAML mapping whose keys are tree-root accessor slots
    (``samples:``, ``projects:`` etc.) and whose values are lists of
    instance dicts. Identity is by the ``id`` slot on each instance.

    Examples:

        mosaic ingest --file bundle.yaml --validate-schema schema.yaml

        mosaic ingest --file bundle.yaml --validate-schema schema.yaml --dry-run

        mosaic ingest --file bundle.yaml --validate-schema schema.yaml --db-path data/store.db

        mosaic ingest --type csv --file donors.csv --config donors_mapping.yaml
    """
    from mosaic.cli.commands.ingest import IngestError, ingest_linkml_yaml

    if file and not loader_type:
        file_path = Path(file)
        if not file_path.exists():
            typer.echo(f"Error: File not found: {file_path}", err=True)
            raise typer.Exit(1)

        if validate_schema and not Path(validate_schema).exists():
            typer.echo(
                f"Error: Schema not found: {validate_schema}", err=True
            )
            raise typer.Exit(1)

        try:
            registry = _build_schema_registry(validate_schema)
        except Exception as e:
            typer.echo(f"Error: Invalid LinkML schema: {e}", err=True)
            raise typer.Exit(1)

        if dry_run:
            try:
                import yaml as _yaml

                parsed = _yaml.safe_load(file_path.read_text(encoding="utf-8"))
            except Exception as e:
                typer.echo(f"Error: Failed to parse YAML: {e}", err=True)
                raise typer.Exit(1)
            if not isinstance(parsed, dict):
                typer.echo(
                    "Error: Instance file must be a YAML mapping "
                    "(tree-root bundle).",
                    err=True,
                )
                raise typer.Exit(1)
            errors = registry.validate(parsed, registry.tree_root_class_name())
            if errors:
                typer.echo(
                    f"Error: {file_path}: {len(errors)} validation "
                    f"error(s):",
                    err=True,
                )
                for err in errors:
                    typer.echo(f"  - {err}", err=True)
                raise typer.Exit(1)
            typer.echo(f"[dry-run] {file_path.name}: bundle validates.")
            return

        client = _get_client(db_path=db_path, schema_path=validate_schema)
        try:
            result = ingest_linkml_yaml(file_path, client, registry)
        except IngestError as e:
            typer.echo(f"Error: {e}", err=True)
            raise typer.Exit(1)

        typer.echo(
            f"Ingested {file_path.name}: "
            f"created={result.created} updated={result.updated} "
            f"errors={result.errors}"
        )
        for msg in result.error_messages:
            typer.echo(f"  Error: {msg}", err=True)
        if result.errors:
            raise typer.Exit(1)

    elif loader_type:
        # Generic loader path (csv / json / sql)
        _run_generic_loader(loader_type, file, config, dry_run, db_path)

    elif config:
        # Legacy: --config only (DataSources format). Process and exit without error.
        _run_legacy_data_sources(config, dry_run)

    else:
        typer.echo(
            "Error: Provide --file (LinkML-native instance YAML) or "
            "--type + --config for a generic loader.",
            err=True,
        )
        raise typer.Exit(1)


def _run_generic_loader(
    loader_type: str,
    file: str | None,
    config: str | None,
    dry_run: bool,
    db_path: str | None = None,
) -> None:
    """Run a generic loader (csv/json/sql) with an optional config file."""
    import yaml as _yaml

    loader_config: dict = {}
    if config:
        config_path = Path(config)
        if not config_path.exists():
            typer.echo(f"Error: Config file not found: {config_path}", err=True)
            raise typer.Exit(1)
        loader_config = _yaml.safe_load(config_path.read_text()) or {}

    if file:
        loader_config.setdefault("source_file", file)

    loader_type = loader_type.lower()
    if loader_type == "csv":
        from mosaic.core.loaders.csv import CSVLoader
        loader = CSVLoader(loader_config)
    elif loader_type == "json":
        from mosaic.core.loaders.json import JSONLoader
        loader = JSONLoader(loader_config)
    elif loader_type == "sql":
        from mosaic.core.loaders.sql import SQLLoader
        loader = SQLLoader(loader_config)
    else:
        typer.echo(f"Error: Unknown loader type '{loader_type}'. Supported: csv, json, sql", err=True)
        raise typer.Exit(1)

    from mosaic.core.loaders.pipeline import IngestPipeline

    client = _get_client(db_path=db_path)
    pipeline = IngestPipeline(client=client, loader=loader)
    result = pipeline.run(dry_run=dry_run)

    action = "[dry-run] Would ingest" if dry_run else "Ingested"
    typer.echo(
        f"{action} via {loader_type}: "
        f"created={result.created} updated={result.updated} "
        f"unchanged={result.unchanged} errors={result.errors}"
    )
    for msg in result.error_messages:
        typer.echo(f"  Error: {msg}", err=True)
    if result.errors:
        raise typer.Exit(1)


